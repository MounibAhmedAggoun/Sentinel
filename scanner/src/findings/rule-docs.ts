import type { CatalogEntry } from './catalog.js';

export interface RuleDocFix {
  /** The software the snippet is for, e.g. "nginx". */
  server: string;
  snippet: string;
}

export interface RuleDocReference {
  title: string;
  url: string;
}

/** The written part of a rule's page. The facts (ID, title, severity) come from the catalog. */
export interface RuleDocContent {
  /** Why the observation can matter. Never claims the site is vulnerable. */
  why: string;
  /** When the finding can be expected or harmless. */
  falsePositives: string;
  fixes: readonly RuleDocFix[];
  references: readonly RuleDocReference[];
}

/** Markdown would read a bare angle bracket as HTML, so write it as text. */
function text(value: string): string {
  return value.replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** A code block whose fence is longer than any run of backticks inside it. */
function fenced(code: string): string {
  const longest = Math.max(0, ...(code.match(/`+/g) ?? []).map((run) => run.length));
  const fence = '`'.repeat(Math.max(3, longest + 1));
  return `${fence}\n${code}\n${fence}`;
}

/** One rule's documentation page as Markdown. Pure: it returns text and writes nothing. */
export function renderRulePage(entry: CatalogEntry, content: RuleDocContent): string {
  const lines: string[] = [];

  lines.push(`# ${entry.id}: ${text(entry.title)}`, '');
  lines.push(`- **Area:** ${entry.area}`);
  lines.push(`- **Severity:** ${entry.severities.join(', ')}`, '');

  lines.push('## What is observed', '', text(entry.summary), '');
  lines.push('## Why it can matter', '', text(content.why), '');
  lines.push('## False positives', '', text(content.falsePositives), '');

  if (content.fixes.length > 0) {
    lines.push('## How to fix', '');
    for (const fix of content.fixes) {
      lines.push(`### ${text(fix.server)}`, '', fenced(fix.snippet), '');
    }
  }

  if (content.references.length > 0) {
    lines.push('## References', '');
    for (const reference of content.references) {
      lines.push(`- [${text(reference.title)}](${reference.url})`);
    }
    lines.push('');
  }

  lines.push(
    '_This page is generated by `npm run export-rule-docs`. Edit the rule content in the source, not this file._',
    '',
  );

  return lines.join('\n');
}

/** The index page listing every documented rule. */
export function renderRuleIndex(
  catalog: readonly CatalogEntry[],
  documented: ReadonlySet<string>,
): string {
  const lines: string[] = ['# Sentinel rules', ''];
  lines.push('| Rule | Severity | Finding |', '| --- | --- | --- |');
  for (const entry of catalog) {
    if (!documented.has(entry.id)) continue;
    lines.push(
      `| [${entry.id}](${entry.id}.md) | ${entry.severities.join(', ')} | ${text(entry.title)} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}
